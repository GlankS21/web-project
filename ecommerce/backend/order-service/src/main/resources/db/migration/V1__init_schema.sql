-- order-service schema: orders with their lines and status timeline, and the transactional outbox

CREATE TABLE orders
(
    id                     UUID PRIMARY KEY,
    order_number           VARCHAR(30)    NOT NULL,
    user_id                UUID           NOT NULL,
    user_email             VARCHAR(255)   NOT NULL,
    status                 VARCHAR(20)    NOT NULL,
    payment_method         VARCHAR(20)    NOT NULL,
    subtotal               NUMERIC(14, 2) NOT NULL,
    shipping_fee           NUMERIC(14, 2) NOT NULL,
    total_amount           NUMERIC(14, 2) NOT NULL,
    currency               VARCHAR(3)     NOT NULL,
    -- shipping address copied at checkout
    recipient_name         VARCHAR(150)   NOT NULL,
    phone_number           VARCHAR(20)    NOT NULL,
    address_line1          VARCHAR(255)   NOT NULL,
    address_line2          VARCHAR(255),
    ward                   VARCHAR(100),
    district               VARCHAR(100),
    city                   VARCHAR(100)   NOT NULL,
    postal_code            VARCHAR(20),
    country_code           VARCHAR(2)     NOT NULL,
    note                   VARCHAR(500),
    idempotency_key        VARCHAR(100),
    cancellation_reason    VARCHAR(500),
    payment_id             UUID,
    payment_transaction_id VARCHAR(100),
    paid_at                TIMESTAMPTZ,
    shipped_at             TIMESTAMPTZ,
    delivered_at           TIMESTAMPTZ,
    cancelled_at           TIMESTAMPTZ,
    created_at             TIMESTAMPTZ    NOT NULL,
    updated_at             TIMESTAMPTZ    NOT NULL,
    version                BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT uk_orders_order_number UNIQUE (order_number),
    -- NULL keys are distinct, so orders placed without a key never collide
    CONSTRAINT uk_orders_user_idempotency_key UNIQUE (user_id, idempotency_key),
    CONSTRAINT ck_orders_status CHECK (status IN
                                       ('PENDING', 'AWAITING_PAYMENT', 'PAID', 'SHIPPED', 'DELIVERED', 'CANCELLED')),
    CONSTRAINT ck_orders_payment_method CHECK (payment_method IN ('COD', 'CARD', 'E_WALLET')),
    CONSTRAINT ck_orders_amounts CHECK (subtotal > 0 AND shipping_fee >= 0 AND total_amount = subtotal + shipping_fee)
);

CREATE INDEX idx_orders_user_created ON orders (user_id, created_at DESC);
CREATE INDEX idx_orders_status_created ON orders (status, created_at);

CREATE TABLE order_items
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      UUID           NOT NULL,
    product_id    BIGINT         NOT NULL,
    sku           VARCHAR(64)    NOT NULL,
    product_name  VARCHAR(200)   NOT NULL,
    thumbnail_url VARCHAR(1000),
    unit_price    NUMERIC(14, 2) NOT NULL,
    quantity      INT            NOT NULL,
    line_total    NUMERIC(14, 2) NOT NULL,
    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT uk_order_items_product UNIQUE (order_id, product_id),
    CONSTRAINT ck_order_items_quantity CHECK (quantity > 0),
    CONSTRAINT ck_order_items_amounts CHECK (unit_price > 0 AND line_total = unit_price * quantity)
);

-- Append-only timeline of status changes
CREATE TABLE order_status_history
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    UUID        NOT NULL,
    from_status VARCHAR(20),
    to_status   VARCHAR(20) NOT NULL,
    reason      VARCHAR(500),
    changed_by  UUID,
    created_at  TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_order_status_history_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE
);

CREATE INDEX idx_order_status_history_order ON order_status_history (order_id, id);

-- Events written in the same transaction as the state change, relayed to RabbitMQ by a poller
CREATE TABLE outbox_events
(
    id             UUID PRIMARY KEY,
    aggregate_id   VARCHAR(100)  NOT NULL,
    exchange       VARCHAR(255)  NOT NULL,
    routing_key    VARCHAR(255)  NOT NULL,
    event_type     VARCHAR(255)  NOT NULL,
    payload        TEXT          NOT NULL,
    correlation_id VARCHAR(64),
    created_at     TIMESTAMPTZ   NOT NULL,
    published_at   TIMESTAMPTZ,
    attempts       INT           NOT NULL DEFAULT 0,
    last_error     VARCHAR(1000)
);

CREATE INDEX idx_outbox_events_pending ON outbox_events (created_at) WHERE published_at IS NULL;
CREATE INDEX idx_outbox_events_published ON outbox_events (published_at) WHERE published_at IS NOT NULL;
