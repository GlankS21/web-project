-- cart-service schema: one cart per customer and its lines

CREATE TABLE carts
(
    id         UUID PRIMARY KEY,
    user_id    UUID        NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    version    BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT uk_carts_user UNIQUE (user_id)
);

-- Product data is a snapshot taken when the line was last changed; prices are refreshed on read
CREATE TABLE cart_items
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id       UUID           NOT NULL,
    product_id    BIGINT         NOT NULL,
    sku           VARCHAR(64)    NOT NULL,
    product_name  VARCHAR(200)   NOT NULL,
    thumbnail_url VARCHAR(1000),
    unit_price    NUMERIC(14, 2) NOT NULL,
    currency      VARCHAR(3)     NOT NULL,
    quantity      INT            NOT NULL,
    created_at    TIMESTAMPTZ    NOT NULL,
    updated_at    TIMESTAMPTZ    NOT NULL,
    CONSTRAINT fk_cart_items_cart FOREIGN KEY (cart_id) REFERENCES carts (id) ON DELETE CASCADE,
    CONSTRAINT uk_cart_items_product UNIQUE (cart_id, product_id),
    CONSTRAINT ck_cart_items_quantity CHECK (quantity > 0)
);
