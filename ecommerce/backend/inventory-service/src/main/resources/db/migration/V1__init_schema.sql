-- inventory-service schema: stock levels, saga reservations, stock ledger and transactional outbox

-- One row per product (product id from product-service). available = on_hand - reserved.
CREATE TABLE inventory_items
(
    product_id          BIGINT PRIMARY KEY,
    sku                 VARCHAR(64),
    quantity_on_hand    INT         NOT NULL DEFAULT 0,
    quantity_reserved   INT         NOT NULL DEFAULT 0,
    low_stock_threshold INT         NOT NULL DEFAULT 5,
    created_at          TIMESTAMPTZ NOT NULL,
    updated_at          TIMESTAMPTZ NOT NULL,
    version             BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT ck_inventory_items_reserved_non_negative CHECK (quantity_reserved >= 0),
    CONSTRAINT ck_inventory_items_reserved_within_on_hand CHECK (quantity_on_hand >= quantity_reserved),
    CONSTRAINT ck_inventory_items_threshold_non_negative CHECK (low_stock_threshold >= 0)
);

CREATE INDEX idx_inventory_items_sku ON inventory_items (sku);

-- Outcome of order.created for one order; the unique order id makes saga steps idempotent.
CREATE TABLE stock_reservations
(
    id             UUID PRIMARY KEY,
    order_id       UUID        NOT NULL,
    order_number   VARCHAR(50) NOT NULL,
    status         VARCHAR(20) NOT NULL,
    failure_reason VARCHAR(500),
    created_at     TIMESTAMPTZ NOT NULL,
    updated_at     TIMESTAMPTZ NOT NULL,
    version        BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT uk_stock_reservations_order UNIQUE (order_id),
    CONSTRAINT ck_stock_reservations_status CHECK (status IN ('RESERVED', 'FAILED', 'COMMITTED', 'RELEASED'))
);

CREATE TABLE stock_reservation_items
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id UUID   NOT NULL,
    product_id     BIGINT NOT NULL,
    quantity       INT    NOT NULL,
    CONSTRAINT fk_stock_reservation_items_reservation FOREIGN KEY (reservation_id)
        REFERENCES stock_reservations (id) ON DELETE CASCADE,
    CONSTRAINT uk_stock_reservation_items_product UNIQUE (reservation_id, product_id),
    CONSTRAINT ck_stock_reservation_items_quantity CHECK (quantity > 0)
);

-- Append-only ledger of every change to on-hand or reserved quantities
CREATE TABLE stock_movements
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id        BIGINT      NOT NULL,
    type              VARCHAR(20) NOT NULL,
    on_hand_change    INT         NOT NULL,
    reserved_change   INT         NOT NULL,
    on_hand_after     INT         NOT NULL,
    reserved_after    INT         NOT NULL,
    reference         VARCHAR(100),
    reason            VARCHAR(255),
    actor_id          UUID,
    created_at        TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_stock_movements_item FOREIGN KEY (product_id) REFERENCES inventory_items (product_id),
    CONSTRAINT ck_stock_movements_type CHECK (type IN ('ADJUSTMENT', 'RESERVATION', 'RELEASE', 'SALE'))
);

CREATE INDEX idx_stock_movements_product_created ON stock_movements (product_id, created_at DESC);

-- Events written in the same transaction as the state change, relayed to RabbitMQ by a poller
CREATE TABLE outbox_events
(
    id             UUID PRIMARY KEY,
    aggregate_id   VARCHAR(100)  NOT NULL,
    exchange       VARCHAR(255)  NOT NULL,
    routing_key    VARCHAR(255)  NOT NULL,
    event_type     VARCHAR(255)  NOT NULL,
    payload        TEXT          NOT NULL,
    correlation_id VARCHAR(64),
    created_at     TIMESTAMPTZ   NOT NULL,
    published_at   TIMESTAMPTZ,
    attempts       INT           NOT NULL DEFAULT 0,
    last_error     VARCHAR(1000)
);

CREATE INDEX idx_outbox_events_pending ON outbox_events (created_at) WHERE published_at IS NULL;
CREATE INDEX idx_outbox_events_published ON outbox_events (published_at) WHERE published_at IS NOT NULL;
