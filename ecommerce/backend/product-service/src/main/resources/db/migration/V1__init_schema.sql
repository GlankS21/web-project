-- product-service schema: two-level category tree, products and their images

CREATE TABLE categories
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    slug        VARCHAR(120) NOT NULL,
    description VARCHAR(500),
    parent_id   BIGINT,
    sort_order  INT          NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ  NOT NULL,
    updated_at  TIMESTAMPTZ  NOT NULL,
    version     BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_categories_slug UNIQUE (slug),
    CONSTRAINT fk_categories_parent FOREIGN KEY (parent_id) REFERENCES categories (id),
    CONSTRAINT ck_categories_not_own_parent CHECK (parent_id IS NULL OR parent_id <> id)
);

CREATE INDEX idx_categories_parent ON categories (parent_id);

CREATE TABLE products
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku               VARCHAR(64)    NOT NULL,
    name              VARCHAR(200)   NOT NULL,
    slug              VARCHAR(220)   NOT NULL,
    short_description VARCHAR(500),
    description       TEXT,
    brand             VARCHAR(100),
    price             NUMERIC(14, 2) NOT NULL,
    compare_at_price  NUMERIC(14, 2),
    category_id       BIGINT         NOT NULL,
    status            VARCHAR(20)    NOT NULL,
    created_at        TIMESTAMPTZ    NOT NULL,
    updated_at        TIMESTAMPTZ    NOT NULL,
    version           BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT uk_products_sku UNIQUE (sku),
    CONSTRAINT uk_products_slug UNIQUE (slug),
    CONSTRAINT fk_products_category FOREIGN KEY (category_id) REFERENCES categories (id),
    CONSTRAINT ck_products_price_positive CHECK (price > 0),
    CONSTRAINT ck_products_compare_at_price CHECK (compare_at_price IS NULL OR compare_at_price > price),
    CONSTRAINT ck_products_status CHECK (status IN ('DRAFT', 'ACTIVE', 'ARCHIVED'))
);

CREATE INDEX idx_products_category ON products (category_id);
CREATE INDEX idx_products_status_created ON products (status, created_at DESC);
CREATE INDEX idx_products_price ON products (price);
CREATE INDEX idx_products_brand ON products (lower(brand));

CREATE TABLE product_images
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT        NOT NULL,
    url        VARCHAR(1000) NOT NULL,
    alt_text   VARCHAR(255),
    sort_order INT           NOT NULL DEFAULT 0,
    CONSTRAINT fk_product_images_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE
);

CREATE INDEX idx_product_images_product ON product_images (product_id, sort_order);
